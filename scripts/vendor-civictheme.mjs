// Usage: node scripts/vendor-civictheme.mjs [path-to-uikit-checkout]   (default .upstream/uikit)
import {
  readdirSync,
  statSync,
  mkdirSync,
  copyFileSync,
  writeFileSync,
  readFileSync,
  rmSync,
  existsSync,
} from 'node:fs';
import { join, relative, dirname, basename } from 'node:path';
import { execSync } from 'node:child_process';

const root = join(dirname(new URL(import.meta.url).pathname), '..');
const uikit = process.argv[2] ?? join(root, '.upstream/uikit');
const twig = join(uikit, 'packages/twig');
const components = join(twig, 'components');
const out = {
  scss: join(root, 'src/civictheme/scss'),
  js: join(root, 'src/civictheme/js/behaviours'),
  icons: join(root, 'src/civictheme/components/00-base/icons.ts'),
  pub: join(root, 'public/civictheme'),
};

const walk = (d) =>
  readdirSync(d).flatMap((n) => {
    const p = join(d, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
const isStory = (p) => /\.stories\./.test(p);
const isVariablesFile = (p) => /(^|\/)_?variables(\.base|\.components)?\.scss$/.test(p);

// 1. SCSS tree (minus stories, style.scss, style.stories.scss) + explicit index
// The two theming files (variables.base.scss / variables.components.scss) are hand-authored once at the
// SCSS ROOT (sibling of 00-base) — that is where 00-base/variables.scss's own `@import '../variables.base'`
// resolves relative to its vendored location — so wipe everything else in out.scss but leave them untouched.
const THEMING_FILES = ['variables.base.scss', 'variables.components.scss'];
if (existsSync(out.scss)) {
  for (const entry of readdirSync(out.scss)) {
    if (THEMING_FILES.includes(entry)) continue;
    rmSync(join(out.scss, entry), { recursive: true, force: true });
  }
} else {
  mkdirSync(out.scss, { recursive: true });
}
const scssFiles = walk(components).filter(
  (p) => p.endsWith('.scss') && !isStory(p) && !/\/style(\.stories)?\.scss$/.test(p)
);
for (const f of scssFiles) {
  // variables.base/components at the components root are the THEMING files; they live at the scss root (see above).
  const rel = relative(components, f);
  if (/^variables\.(base|components)\.scss$/.test(rel)) continue;
  const dest = join(out.scss, rel);
  mkdirSync(dirname(dest), { recursive: true });
  copyFileSync(f, dest);
}
const layers = ['00-base', '01-atoms', '02-molecules', '03-organisms', '04-templates', '05-pages'];
let index = "// Generated by scripts/vendor-civictheme.mjs — do not edit.\n@import '00-base/variables';\n";
// Upstream builds style.css_variables.scss (at the components root, alongside style.scss) as a SEPARATE
// stylesheet emitting the --ct-color-* custom properties; it lives outside the layer folders so the walk
// below never reaches it. Wire it in here, right after the Sass variables it consumes.
if (existsSync(join(out.scss, 'style.css_variables.scss'))) {
  index += "@import 'style.css_variables';\n";
}
for (const layer of layers) {
  const dir = join(out.scss, layer);
  if (!existsSync(dir)) continue;
  for (const f of walk(dir)
    .filter((p) => p.endsWith('.scss') && !isVariablesFile(p))
    .sort()) {
    index += `@import '${relative(out.scss, f).replace(/\.scss$/, '')}';\n`;
  }
}
writeFileSync(join(out.scss, 'index.scss'), index);
// 00-base/variables.scss imports '../variables.base' and '../variables.components' relative to its own vendored
// location (src/civictheme/scss/00-base/) → the theming files must sit at src/civictheme/scss/variables.*.scss
// (the scss root, sibling of 00-base — created once in Step 3, preserved across re-runs above).

// 2. JS behaviours (non-story, non-test, non-utils)
rmSync(out.js, { recursive: true, force: true });
const jsFiles = walk(components).filter(
  (p) => p.endsWith('.js') && !isStory(p) && !/\.test\.js$/.test(p) && !/\.utils\.js$/.test(p) && !/storybook/.test(p)
);
for (const f of jsFiles) {
  const dest = join(out.js, basename(f));
  mkdirSync(dirname(dest), { recursive: true });
  copyFileSync(f, dest);
}
writeFileSync(
  join(out.js, 'index.js'),
  jsFiles
    .map((f) => `import './${basename(f)}';`)
    .sort()
    .join('\n') + '\n'
);

// 3. Icons → TS symbol map
const iconDir = join(twig, 'assets/icons');
const icons = readdirSync(iconDir)
  .filter((f) => f.endsWith('.svg'))
  .sort();
let ts = '// Generated by scripts/vendor-civictheme.mjs — do not edit.\nexport const icons = {\n';
for (const f of icons)
  ts += `  ${JSON.stringify(f.replace(/\.svg$/, ''))}: ${JSON.stringify(readFileSync(join(iconDir, f), 'utf8').trim())},\n`;
ts += '} as const;\nexport type IconSymbol = keyof typeof icons;\n';
mkdirSync(dirname(out.icons), { recursive: true });
writeFileSync(out.icons, ts);

// 4. Backgrounds + logos → public/civictheme
for (const sub of ['backgrounds', 'logos']) {
  const src = join(twig, 'assets', sub);
  const dest = join(out.pub, sub);
  rmSync(dest, { recursive: true, force: true });
  mkdirSync(dest, { recursive: true });
  for (const f of readdirSync(src)) copyFileSync(join(src, f), join(dest, f));
}

// 5. NOTICE version/commit
const version = JSON.parse(readFileSync(join(uikit, 'package.json'), 'utf8')).version;
let commit = 'unknown';
try {
  commit = execSync('git rev-parse HEAD', { cwd: uikit }).toString().trim();
} catch {}
const notice = join(root, 'NOTICE.md');
writeFileSync(
  notice,
  readFileSync(notice, 'utf8')
    .replace(/- Version: .*/, `- Version: ${version}`)
    .replace(/- Commit: .*/, `- Commit: ${commit}`)
);
console.log(
  `vendored ${scssFiles.length} scss, ${jsFiles.length} js, ${icons.length} icons from uikit ${version} (${commit.slice(0, 7)})`
);
